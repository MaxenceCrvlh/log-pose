"""Refresh data/src/ from the official Japanese card list (onepiece-cardgame.com/cardlist).

Log Pose used to read the punk-records dataset, but its Japanese half is only regenerated by hand
now and then (it stopped at September 2026, so EB05 never arrived). This reads the official list
directly, so a new set shows up the week Bandai publishes it.

data/src/<pack id>.json  one file per product on the official list: [{id, name, rarity, category, img_full_url, info}]
data/src/packs.json      {pack id: product title as written on the official list}

Careful by design: a product that fails to download, comes back empty or comes back much smaller
than last time keeps its previous file, so a bad day on the official site never empties the app.

Usage:  python tools/fetch_official.py [--only 550205,550118] [--delay 1.0]
        python tools/fetch_official.py --parse page.html     (print what a saved page parses to)
"""
import argparse, html, json, pathlib, re, sys, time, urllib.parse, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "src"
HOST = "https://www.onepiece-cardgame.com"
UA = {"User-Agent": "log-pose-builder/1.0 (personal collection checklist; github action)",
      "Accept-Language": "ja,en;q=0.5"}
RARITY = {"C": "Common", "UC": "Uncommon", "R": "Rare", "SR": "SuperRare", "SEC": "SecretRare", "L": "Leader",
          "SP": "Special", "SPカード": "Special", "TR": "TreasureRare", "P": "Promo"}
CATEGORY = {"LEADER": "Leader", "CHARACTER": "Character", "EVENT": "Event", "STAGE": "Stage", "DON": "Don",
            "DON!!": "Don", "リーダー": "Leader", "キャラ": "Character", "キャラクター": "Character",
            "イベント": "Event", "ステージ": "Stage", "ドン!!": "Don"}
CARD_ID = re.compile(r"^[A-Z]{1,4}\d{0,2}-\d{3}(?:_[a-z]\d+)?$")
# products the app reads cards from when the official list of products cannot be read:
# starters, boosters, extra boosters, premium boosters, family deck, limited products, promos
FAMILIES = {"5500": "ST", "5501": "OP", "5502": "EB", "5503": "PRB"}


def get(url, tries=3):
    last = None
    for n in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return r.read().decode("utf-8", "replace")
        except Exception as e:                       # noqa: BLE001 - any failure is retried, then reported
            last = e
            time.sleep(3 * (n + 1))
    raise RuntimeError(f"{url}: {last}")


def text(fragment):
    """Visible text of an HTML fragment."""
    t = re.sub(r"(?is)<(script|style)\b.*?</\1>", "", fragment)
    t = re.sub(r"(?s)<[^>]+>", " ", t)
    return re.sub(r"\s+", " ", html.unescape(t)).strip()


def attr(tag, name):
    m = re.search(r"""\b%s\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))""" % re.escape(name), tag, re.I)
    return html.unescape(next(g for g in m.groups() if g is not None)) if m else None


def div(block, cls):
    """Inner HTML of the first <div class="... cls ..."> in block (these divs hold no nested div)."""
    m = re.search(r"""(?is)<div\b[^>]*\bclass\s*=\s*["'][^"']*\b%s\b[^"']*["'][^>]*>(.*?)</div>""" % re.escape(cls), block)
    return m.group(1) if m else None


def parse_packs(page):
    """{pack id: title} from the product selector (<select id="series">)."""
    m = re.search(r"""(?is)<select\b[^>]*\bid\s*=\s*["']?series["']?[^>]*>(.*?)</select>""", page)
    out = {}
    for o in re.finditer(r"(?is)<option\b([^>]*)>(.*?)(?=</option>|<option\b|$)", m.group(1) if m else ""):
        pid = (attr("<o " + o.group(1) + ">", "value") or "").strip()
        if re.fullmatch(r"\d{6}", pid):
            out[pid] = text(o.group(2))
    return out


def parse_cards(page):
    """Cards of one product page. Each card is a <dl id="OP01-001"> block."""
    cards, seen = [], set()
    for m in re.finditer(r"(?is)<dl\b([^>]*)>(.*?)</dl>", page):
        cid = (attr("<dl " + m.group(1) + ">", "id") or "").strip()
        block = m.group(2)
        info = div(block, "infoCol")
        if not cid or info is None or cid in seen:
            continue
        spans = [text(s) for s in re.findall(r"(?is)<span\b[^>]*>(.*?)</span>", info)]
        if len(spans) < 3:                              # "OP01-001 | L | LEADER" without spans
            spans = [s.strip() for s in text(info).split("|")]
        if len(spans) < 3 or not CARD_ID.match(cid):
            print(f"  skipped a block that does not look like a card: {cid!r}")
            continue
        rar = re.sub(r"\s+", "", spans[1])
        cat = spans[2].strip()
        img = None
        front = div(block, "frontCol") or block
        im = re.search(r"(?is)<img\b[^>]*>", front)
        if im:
            img = attr(im.group(0), "data-src") or attr(im.group(0), "src")
        if img:
            img = urllib.parse.urljoin(HOST + "/cardlist/", img).split("?")[0]
        else:
            img = f"{HOST}/images/cardlist/card/{cid}.png"
        got = div(block, "getInfo")
        if got is not None:
            got = text(re.sub(r"(?is)<h3\b.*?</h3>", "", got)).strip("-－ ")
        seen.add(cid)
        cards.append({"id": cid, "name": text(div(block, "cardName") or ""),
                      "rarity": RARITY.get(rar, rar), "category": CATEGORY.get(cat.upper(), CATEGORY.get(cat, cat.title())),
                      "img_full_url": img, **({"info": got} if got else {})})
    return cards


def dump(cards):
    return "[\n" + ",\n".join(json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in cards) + "\n]\n"


def prefix_ok(pid, cards):
    """A product we only guessed at must hold that product's own cards (OP18-...)."""
    fam = FAMILIES.get(pid[:4])
    if not fam:
        return False
    want = f"{fam}{pid[4:]}-"
    return sum(c["id"].startswith(want) for c in cards) >= max(5, len(cards) // 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="comma-separated pack ids (default: every product)")
    ap.add_argument("--delay", type=float, default=1.0)
    ap.add_argument("--parse", help="parse a saved HTML page and print the result (no download)")
    a = ap.parse_args()

    if a.parse:
        page = pathlib.Path(a.parse).read_text(encoding="utf-8")
        cards = parse_cards(page)
        print(json.dumps({"packs": parse_packs(page), "cards": len(cards), "first": cards[:3]}, ensure_ascii=False, indent=1))
        return 0

    SRC.mkdir(parents=True, exist_ok=True)
    have = {f.stem: json.loads(f.read_text(encoding="utf-8")) for f in SRC.glob("[0-9]*.json")}
    titles_file = SRC / "packs.json"
    titles = json.loads(titles_file.read_text(encoding="utf-8")) if titles_file.exists() else {}

    listed = {}
    try:
        listed = parse_packs(get(f"{HOST}/cardlist/"))
    except Exception as e:                           # noqa: BLE001
        print(f"Could not read the list of products: {e}")
    guessed = set()
    if listed:
        print(f"{len(listed)} products on the official list")
        todo = sorted(listed)
    else:
        # no selector found: refresh what we know and try the next number of each series
        print("No product selector found - refreshing known products and trying the next set numbers.")
        for fam in FAMILIES:
            nums = [int(p[4:]) for p in have if p.startswith(fam)]
            for n in range(max(nums, default=0) + 1, max(nums, default=0) + 3):
                guessed.add(f"{fam}{n:02d}")
        todo = sorted(set(have) | guessed)
    if a.only:
        todo = [p for p in a.only.split(",") if p]

    changed = failed = 0
    for pid in todo:
        try:
            cards = parse_cards(get(f"{HOST}/cardlist/?series={pid}"))
        except Exception as e:                       # noqa: BLE001
            failed += 1
            print(f"{pid}: download failed, keeping the previous list ({e})")
            continue
        finally:
            time.sleep(a.delay)
        old = have.get(pid, [])
        if not cards:
            if pid not in guessed:
                failed += bool(old)
                print(f"{pid}: no cards on the page" + (", keeping the previous list" if old else ""))
            continue
        if pid in guessed and not prefix_ok(pid, cards):
            continue
        old_ids, new_ids = {c["id"] for c in old}, {c["id"] for c in cards}
        if old and (len(cards) < 0.8 * len(old) or len(old_ids & new_ids) < 0.5 * len(old_ids)):
            failed += 1
            print(f"{pid}: page looks wrong ({len(cards)} cards, {len(old_ids & new_ids)} of the {len(old)} known) - keeping the previous list")
            continue
        if not old:
            print(f"{pid}: NEW product, {len(cards)} cards - {listed.get(pid, '')}")
        elif new_ids != old_ids:
            print(f"{pid}: {len(new_ids - old_ids)} added, {len(old_ids - new_ids)} removed")
        out = dump(cards)
        f = SRC / f"{pid}.json"
        if not f.exists() or f.read_text(encoding="utf-8") != out:
            f.write_text(out, encoding="utf-8")
            changed += 1
        if listed.get(pid):
            titles[pid] = listed[pid]

    titles_file.write_text(json.dumps(titles, ensure_ascii=False, indent=0, sort_keys=True) + "\n", encoding="utf-8")
    print(f"{len(todo)} products read, {changed} files updated, {failed} kept from last time")
    if todo and failed == len(todo):
        print("::warning::The official card list could not be read at all - the app keeps last week's list.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
